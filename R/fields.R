# The field registry: the single source of truth for every field a resource
# record may carry. Field grouping, type, cardinality, and which resource types
# a field applies to are declared here as metadata rather than as physical
# nesting, so that records stay flat and project cleanly to a rectangular view.

# Resource-type groupings used by `applies_to`.
