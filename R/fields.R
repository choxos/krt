# Build a name -> spec lookup once per session.
.krt_field_env <- new.env(parent = emptyenv())
.field_index <- function() {
  if (is.null(.krt_field_env$idx)) {
    defs <- .krt_field_defs()
    idx <- stats::setNames(defs, vapply(defs, function(f) f$name, character(1)))
    .krt_field_env$idx <- idx
    .krt_field_env$order <- names(idx)
  }
  .krt_field_env$idx
}

#' Key Resources Table field registry
#'
#' The field registry declares every field a resource record may carry, together
#' with its group, type, cardinality, and the resource types it applies to.
#'
#' @param name A field name.
#' @param resource_type A resource type (one of [krt_resource_types()]).
#' @return `all_fields()` returns a named list of field specifications;
#'   `field_spec()` returns one specification (or `NULL`); `fields_for_type()`
#'   returns the names of fields that apply to a resource type; `field_label()`
#'   returns a human-readable label.
#' @examples
#' str(field_spec("rrid"))
#' fields_for_type("Antibody")
#' @name field_registry
NULL

#' @rdname field_registry
#' @export
all_fields <- function() .field_index()

#' @rdname field_registry
#' @export
field_spec <- function(name) {
  idx <- .field_index()
  idx[[name]]
}

#' @rdname field_registry
#' @export
fields_for_type <- function(resource_type) {
  idx <- .field_index()
  keep <- vapply(idx, function(f) {
    identical(f$applies_to, "all") || resource_type %in% f$applies_to
  }, logical(1))
  names(idx)[keep]
}

#' @rdname field_registry
#' @param locale Optional locale (currently advisory; labels fall back to a
#'   title-cased field name).
#' @export
field_label <- function(name, locale = NULL) {
  spec <- field_spec(name)
  if (is.null(spec)) return(name)
  # Human-readable default: replace underscores, title-case first letter, then
  # pass through the translation domain so localized labels are used when
  # available.
  lbl <- gsub("_", " ", name)
  lbl <- paste0(toupper(substr(lbl, 1L, 1L)), substr(lbl, 2L, nchar(lbl)))
  tr(lbl)
}

#' Coerce a field value to its declared type.
#'
#' Light, non-destructive coercion used when building resource records. Enum
#' fields are lower/normalized where the vocabulary is lowercase; unknown enum
#' values are passed through unchanged (validation reports on them separately).
#'
#' @param name Field name.
#' @param value The value to coerce.
#' @return The coerced value.
#' @export
#' @examples
#' coerce_field("new_or_reuse", "NEW")
#' coerce_field("pmid", 12345)
coerce_field <- function(name, value) {
  if (is.null(value)) return(NULL)
  spec <- field_spec(name)
  if (is.null(spec)) return(value)
  switch(spec$type,
    logical = as.logical(value),
    integer = suppressWarnings(as.integer(value)),
    enum = .coerce_enum(name, value, spec$enum),
    # date, uri, string, list all stored as character (list stays a vector)
    as.character(value)
  )
}

#' @noRd
.coerce_enum <- function(name, value, enum_key) {
  v <- as.character(value)
  vocab <- tryCatch(krt_vocab(enum_key), error = function(e) NULL)
  if (is.null(vocab)) return(v)
  # Normalize case for lowercase vocabularies (new_or_reuse, status, ...).
  if (all(vocab == tolower(vocab))) v <- tolower(v)
  v
}
