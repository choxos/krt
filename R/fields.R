# Construct one field spec.
.fld <- function(name, group, type = "string", cardinality = "one",
                 applies_to = "all", enum = NULL, help = "") {
  list(name = name, group = group, type = type, cardinality = cardinality,
       applies_to = applies_to, enum = enum,
       label_key = paste0("field.", name), help = help)
}

